const LANGS = ['tr', 'en', 'de', 'fr', 'es', 'ar', 'it', 'zh', 'ru', 'fa', 'ja', 'pt', 'nl'];
const baseKeys = Object.keys(T.en);
const digitsOf = (value) => (value.replace(/\{\{\w+\}\}/g, '').match(/[0-9]+/g) || []).sort().join();
const problems = [];
const out = {};
for (const lang of LANGS) {
  const table = T[lang];
  for (const key of baseKeys) {
    const value = table[key];
    if (typeof value !== 'string' || !value.trim()) {
      problems.push(`${lang}.${key}: missing`);
      continue;
    }
    if ((T.en[key].match(/\{\{\w+\}\}/g) || []).join() !== (value.match(/\{\{\w+\}\}/g) || []).join()) problems.push(`${lang}.${key}: placeholders`);
    if (digitsOf(value) !== digitsOf(T.en[key])) problems.push(`${lang}.${key}: numbers`);
    if (lang !== 'en' && value.length >= 12 && value === T.en[key]) problems.push(`${lang}.${key}: identical to EN`);
  }
  out[lang] = Object.fromEntries(baseKeys.map((key) => [key, table[key]]));
}
if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}
fs.writeFileSync(
  path.join(__dirname, '..', 'i18n.waveux40.js'),
  `// WAVE UX.40 — settings group headers, guide "start here" flow, paywall value card. Same key set in all 13 languages.\n\nexport const WAVE_UX40_I18N = ${JSON.stringify(out, null, 2)};\n`,
);
