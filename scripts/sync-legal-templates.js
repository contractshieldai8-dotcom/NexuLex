'use strict';
// Vendors the attorney-drafted, CC0-1.0 contract templates from General Legal's public library
// (https://github.com/General-Legal/legal-templates) into constants/contractLibrary/texts/.
//
//   node scripts/sync-legal-templates.js              download the pinned commit and (re)write the text modules
//   node scripts/sync-legal-templates.js --check      fail if the committed modules differ from the pinned commit
//   node scripts/sync-legal-templates.js --from <dir> read <slug>.md files from a local folder instead of the network
//
// Why vendoring (not a git submodule / runtime fetch): EAS cloud builds do not initialise submodules,
// and a contract the user signs must never change underneath them. The commit SHA below is the single
// source of truth; bump it deliberately, review the diff, then re-run `npm run verify`.
const fs = require('fs');
const path = require('path');
const https = require('https');

const REPO = 'General-Legal/legal-templates';
const PINNED_SHA = '6d6805425eabd41bed86fc1e2ec51612760f716c';
const LICENSE = 'CC0-1.0';
const ROOT = path.join(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'constants', 'contractLibrary', 'texts');

/** id = NexuLex template id (matches constants/contractLibrary.js); slug = folder in the upstream repo. */
const TEMPLATES = [
  { id: 'mutual_nda', slug: 'mutual-nda' },
  { id: 'one_way_nda', slug: 'one-way-nda' },
  { id: 'master_services_agreement', slug: 'master-services-agreement' },
  { id: 'advisor_agreement', slug: 'advisor-agreement' },
  { id: 'dpa_global', slug: 'dpa-global' },
  { id: 'terms_of_use', slug: 'terms-of-use' },
  { id: 'privacy_policy_gdpr', slug: 'privacy-policy-gdpr' },
  { id: 'cookie_notice', slug: 'cookie-notice' },
];

const args = process.argv.slice(2);
const check = args.includes('--check');
const fromIdx = args.indexOf('--from');
const fromDir = fromIdx >= 0 ? path.resolve(args[fromIdx + 1] || '') : null;

function download(url) {
  return new Promise((resolve, reject) => {
    https
      .get(url, { headers: { 'User-Agent': 'nexulex-sync' } }, (res) => {
        if (res.statusCode !== 200) {
          res.resume();
          reject(new Error(`${res.statusCode} ${url}`));
          return;
        }
        const chunks = [];
        res.on('data', (c) => chunks.push(c));
        res.on('end', () => resolve(Buffer.concat(chunks).toString('utf8')));
      })
      .on('error', reject);
  });
}

function normalize(md) {
  return String(md)
    .replace(/^\uFEFF/, '')
    .replace(/\r\n?/g, '\n')
    .replace(/\u200d/g, '')
    .replace(/[ \t]+\n/g, '\n')
    .replace(/\n{4,}/g, '\n\n\n')
    .trim();
}

function moduleSource({ id, slug }, text) {
  return `// GENERATED by scripts/sync-legal-templates.js - do not edit by hand.
// Source: https://github.com/${REPO}/blob/${PINNED_SHA}/templates/${slug}/template.md
// License: ${LICENSE} (public domain dedication). Template id: ${id}.
export const CONTRACT_TEXT = ${JSON.stringify(text)};
`;
}

async function main() {
  let problems = 0;
  fs.mkdirSync(OUT_DIR, { recursive: true });
  for (const tpl of TEMPLATES) {
    let raw;
    if (fromDir) raw = fs.readFileSync(path.join(fromDir, `${tpl.slug}.md`), 'utf8');
    else raw = await download(`https://raw.githubusercontent.com/${REPO}/${PINNED_SHA}/templates/${tpl.slug}/template.md`);
    const next = moduleSource(tpl, normalize(raw));
    const file = path.join(OUT_DIR, `${tpl.id}.js`);
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (check) {
      if (current !== next) {
        console.error(`STALE  constants/contractLibrary/texts/${tpl.id}.js - run: node scripts/sync-legal-templates.js`);
        problems += 1;
      }
    } else if (current !== next) {
      fs.writeFileSync(file, next);
      console.log(`wrote  constants/contractLibrary/texts/${tpl.id}.js (${next.length} bytes)`);
    } else {
      console.log(`ok     constants/contractLibrary/texts/${tpl.id}.js`);
    }
  }
  const metaFile = path.join(ROOT, 'constants', 'contractLibrary', 'source.js');
  const meta = `// GENERATED by scripts/sync-legal-templates.js - do not edit by hand.
export const CONTRACT_LIBRARY_SOURCE = {
  repo: '${REPO}',
  url: 'https://github.com/${REPO}',
  commit: '${PINNED_SHA}',
  license: '${LICENSE}',
  author: 'General Legal, PC',
};
`;
  const currentMeta = fs.existsSync(metaFile) ? fs.readFileSync(metaFile, 'utf8') : null;
  if (check) {
    if (currentMeta !== meta) {
      console.error('STALE  constants/contractLibrary/source.js');
      problems += 1;
    }
  } else if (currentMeta !== meta) {
    fs.writeFileSync(metaFile, meta);
    console.log('wrote  constants/contractLibrary/source.js');
  }
  if (problems) process.exit(1);
}

main().catch((error) => {
  console.error(error.message || error);
  process.exit(1);
});
