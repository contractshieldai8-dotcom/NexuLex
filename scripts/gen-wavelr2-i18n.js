const langs = ['tr', 'en', 'de', 'fr', 'es', 'ar', 'it', 'zh', 'ru', 'fa', 'ja', 'pt', 'nl'];
const baseKeys = Object.keys(T.en);
const out = {};
for (const lang of langs) {
  const table = T[lang];
  if (!table) throw new Error(`Missing ${lang} translation table`);
  const missing = baseKeys.filter((key) => typeof table[key] !== 'string' || !table[key].trim());
  const extra = Object.keys(table).filter((key) => !baseKeys.includes(key));
  if (missing.length || extra.length) throw new Error(`${lang}: missing=[${missing}] extra=[${extra}]`);
  for (const key of baseKeys) {
    const want = (T.en[key].match(/\{\{\w+\}\}/g) || []).sort().join();
    const got = (table[key].match(/\{\{\w+\}\}/g) || []).sort().join();
    if (want !== got) throw new Error(`${lang}.${key}: placeholders ${got} != ${want}`);
  }
  out[lang] = Object.fromEntries(baseKeys.map((key) => [key, table[key]]));
}
